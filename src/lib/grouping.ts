import { PriceItem } from "../types";

// ---------------------------------------------------------------------------
// Общая логика группировки похожих товаров (используется и в Catalog.tsx —
// список/сетка каталога, и в ProductPage.tsx — блок "похожие варианты").
// ВАЖНО: это единственное место, где живёт stripToBaseName. Если скопировать
// эту функцию в оба файла отдельно, они рано или поздно разойдутся при правке
// одного без другого, и товары на странице каталога будут группироваться
// иначе, чем на странице товара — этого не должно случиться.
// ---------------------------------------------------------------------------

export interface ItemGroup {
  baseName: string;
  items: PriceItem[];
}

const BND_BEFORE = "(?<![A-Za-zА-Яа-яЁё0-9])";
const BND_AFTER = "(?![A-Za-zА-Яа-яЁё0-9])";
function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Бренды/производители, собранные из реального каталога — режем их ГДЕ УГОДНО
// в строке (не только в конце), т.к. для расходников/крепежа и т.п. бренд
// часто не важен покупателю, и это специально решение — группировать шире,
// принимая единичные неточные объединения ради масштаба (3000+ товаров).
const KNOWN_BRANDS = [
  "TDM", "IEK", "REXANT", "Jazzway", "legrand", "KRANZ", "SHCET", "PROxima", "STARFIX",
  "CHINT", "General", "GENERICA", "OSRAM", "BYLECTRICA", "SIMPLE", "PROconnect",
  "ECOLINE", "ЗЭТАРУС", "ЭРА", "ZETKAMA", "UNIDELTA", "РВК", "Дрогол",
  "БЭЗ", "ЗУБР", "IWELD", "OLIVER", "ГАРАНТ", "Континент", "СЗСМ",
  "VERTO", "KRAFTOOL", "PATRIOT", "BOSCH", "URAGAN", "Remocolor", "Navigator",
];
const KNOWN_COUNTRIES = [
  "Россия", "РОССИЯ", "РФ", "Китай", "КИТАЙ", "Беларусь", "БЕЛАРУСЬ", "РБ",
  "Турция", "Украина", "Франция", "Польша", "ПОЛЬША", "Италия", "Германия",
  "Чехия", "Индия", "США", "Корея", "Тайвань", "Испания", "Латвия", "Литва", "Узбекистан",
];
const BRAND_ALT = KNOWN_BRANDS.map(escapeRegExp).join("|");
const COUNTRY_ALT = KNOWN_COUNTRIES.map(escapeRegExp).join("|");

// Короткие предлоги/союзы — сами по себе ничего не различают, но занимают
// место в лимите "первые 2 значимых слова", из-за чего настоящее различающее
// слово (например, "бетону"/"металлу"/"дереву" после "по") обрезается и
// пропадает. Проверено на реальных данных: без этого списка "Сверло по
// бетону", "Сверло по металлу" и "Сверло по дереву" (физически разные типы
// свёрел, не взаимозаменяемые) сливались в одну группу "Сверло по" —
// пропускаем такие слова при выборе значимых, а не вырезаем из текста целиком
// (для смысла остального названия они не мешают).
const FILLER_WORDS = new Set([
  "по", "для", "и", "с", "со", "от", "из", "на", "под", "к", "у", "о", "об",
  "в", "во", "за", "до", "при", "не", "как",
]);

// Типоразмер батарейки/аккумулятора — это то, что реально определяет
// взаимозаменяемость (AA и AAA физически не подходят друг вместо друга), но
// в названии он всегда идёт 3-м-4-м словом, а не в первых двух — из-за этого
// общая первая часть названия ("Элемент питания", "Батарейка алкалиновая")
// сводила в одну группу совершенно разные по размеру батарейки. Один и тот
// же типоразмер в каталоге пишут по-разному (AA = LR6 = R6), приводим к
// одному виду. "Таблетки" (CR/AG-коды) специально НЕ обобщаем между собой —
// разные номера это разные физические размеры (диаметр/толщина), не варианты
// одного товара.
const BATTERY_SIZE_ALIASES: [RegExp, string][] = [
  [/\b(?:LR20|R20|NBT-?NS-?R20)\b/i, "D"],
  [/\b(?:LR14|R14)\b/i, "C"],
  [/\b(?:LR6|R6|AA)\b/i, "AA"],
  [/\b(?:LR03|R03|AAA)\b/i, "AAA"],
  [/\b(?:6LR61|6F22|Крона)\b/i, "9V"],
  [/\b(?:18650)\b/i, "18650"],
  [/\b(?:16340)\b/i, "16340"],
  [/\bCR(\d{3,4})\b/i, "CR$1"],
  [/\bAG(\d{1,2})\b/i, "AG$1"],
  [/\bLR(\d{3,4})\b/i, "LR$1"],
];

// Цоколь лампы — как и типоразмер батарейки, определяет физическую
// совместимость (лампа E27 не вкрутится в патрон E14), а в названии
// встречается где угодно, но не в первых 2 словах. GU5.3 и G4 обычно
// низковольтные (12В), это тоже фактически другой класс ламп — но сам код
// цоколя уже их различает, отдельно выделять не нужно.
const LAMP_BASE_CODES = ["GX53", "GU10", "GU5.3", "E27", "E14", "E40", "G13", "G9", "G4", "B22", "R7s"];

// Убирает из названия бренд/страну/скобки/любые "числовые" куски (размер, вес,
// артикул, номер модели) — то, что остаётся, обрезается до первых двух
// значимых слов. Это НАМЕРЕННО грубый инструмент: цель — минимизировать число
// карточек-дублей для крупного каталога (3000+ позиций), а не идеальная
// точность группировки. Полное название каждого товара всегда остаётся
// видно в списке вариантов на странице товара, так что даже неточная
// группировка не прячет от покупателя, что именно он выбирает — просто иногда
// в одной группе окажется на 1-2 "соседа" больше, чем формально стоило бы.
export function stripToBaseName(name: string, attrs?: PriceItem["attributes"]): string {
  let s = name;
  // Служебный артикул слитно в самом начале названия через запятую
  // ("HT8D050, Круг шлифовальный...", "IMK00390, Саморез кровельный...") —
  // сдвигает подсчёт "первых 2 значимых слов" на сам артикул, из-за чего
  // товар не попадал в свою же группу с остальными такими же по смыслу.
  // Проверено на реальных данных (24 совпадения по базе) — везде это именно
  // служебный код, а не часть названия.
  s = s.replace(/^[A-ZА-ЯЁ0-9]{4,12},\s*/, "");

  // Спецслучай контакторов/пускателей: напряжение катушки (220В/380В и т.п.)
  // — как и коил лампы/батарейки, это то, что реально определяет
  // совместимость (нельзя переключить контактор на 380В катушкой на 220В),
  // но модельный код содержит и напряжение, и номинал тока слитно одним
  // куском ("КМ-0911220" = ток 9А + напряжение 220В). Проверено на реальных
  // данных: "Контактор КТ-115А" СЕЙЧАС уже неправильно объединяет 220В и
  // 380В версии в одну группу — это баг безопасности, не просто неудобство.
  if (/контактор|пускатель/i.test(s)) {
    // У серии КМ цифровой код после дефиса = ток+напряжение слитно — срезаем
    // его до самой серии, напряжение допишем ниже из текста названия.
    s = s.replace(/(?:^|\s)КМ-\d+/i, " КМ");
    const words2 = s.split(/\s+/).filter((w) => w && !FILLER_WORDS.has(w.toLowerCase()));
    let ctorBase = words2.slice(0, 2).join(" ") || name;
    const voltM = name.match(new RegExp(`${BND_BEFORE}(12|24|36|42|110|220|380)\\s*В${BND_AFTER}`, "i"));
    if (voltM) ctorBase += ` ${voltM[1]}В`;
    return ctorBase;
  }

  // Спецслучай батареек/аккумуляторов — см. комментарий у BATTERY_SIZE_ALIASES
  // выше. Срабатывает только для товаров, где в названии реально есть слово
  // "аккумулятор"/"батаре"/"элемент питания" — чтобы не задеть что-то чужое,
  // где случайно встретится "AA" или "CR" как часть артикула.
  if (/аккумулятор|батаре|элемент\s+питания|эл\.?\s*питания|таблеточ/i.test(s)) {
    for (const [re, label] of BATTERY_SIZE_ALIASES) {
      const m = s.match(re);
      if (m) {
        const kind = /аккумулятор/i.test(s) ? "Аккумулятор" : "Батарейка";
        return `${kind} ${label.replace("$1", m[1] || "")}`;
      }
    }
  }

  // Спецслучай ламп — см. комментарий у LAMP_BASE_CODES. Срабатывает только
  // если в названии есть слово "лампа" (не задевает светодиодные ленты,
  // прожекторы, светильники без цоколя — там код после "E27" и т.п. просто
  // не встретится, и они уйдут в обычную обработку ниже).
  if (/лампа/i.test(s)) {
    for (const code of LAMP_BASE_CODES) {
      if (new RegExp(`${BND_BEFORE}${escapeRegExp(code)}${BND_AFTER}`, "i").test(s)) {
        return `Лампа ${code}`;
      }
    }
  }

  if (attrs) {
    (["power", "voltage", "base", "color_temp", "current", "diameter", "material", "country",
      "standard", "protection", "size", "thread"] as const).forEach((key) => {
      const val = (attrs as any)[key];
      if (!val) return;
      const pattern = escapeRegExp(String(val).trim()).replace(/\\?\s+/g, "\\s*");
      // Границы слова обязательны — без них, например, атрибут material="Сталь"
      // резал бы подстрокой и внутри слова "стальНОЙ" (Сталь+ной), превращая
      // "Фланец стальной" в "Фланец ной". Раньше это было незаметно, но после
      // обрезки базового имени до 2 слов такой огрызок становится всем, что
      // остаётся — критично для группировки.
      try {
        s = s.replace(new RegExp(`${BND_BEFORE}${pattern}${BND_AFTER}`, "gi"), " ");
      } catch {
        s = s.split(val).join(" ");
      }
    });
  }

  // Спец-случай: ТМЛ (медный наконечник под опрессовку, ГОСТ 7386-80) в базе
  // называется то "Наконечник медный ТМЛ...", то "Наконечник кабельный
  // медный ТМЛ...", то сокращённо "Каб.нак. медно-луженые ТМЛ-..." — по сути
  // одна и та же серия, просто слова расставлены/сокращены по-разному, из-за
  // чего первые 2 слова получались разными и группировка их разбивала.
  // Проверено на реальных данных: НЕ трогаем болтовые (Наконечник кабельный
  // болтовой НБ...) и штифтовые (НШМЛ) наконечники — это другой тип
  // крепления (под болт / под штифт, а не под опрессовку), объединять их с
  // ТМЛ было бы уже ошибкой.
  if (
    new RegExp(`${BND_BEFORE}ТМЛ${BND_AFTER}`, "i").test(s) &&
    !/болтов|штифтов/i.test(s)
  ) {
    return "Наконечник ТМЛ";
  }

  // Спец-случай: у насосов ЭЦВ/СПА число после буквенного кода — это класс
  // товара (диаметр скважины, физически несовместимые между собой размеры),
  // а не размер варианта одной и той же модели — его нужно сохранить.
  s = s.replace(/(ЭЦВ\s*\d+)[-\s].*$/i, "$1");
  s = s.replace(/(СПА\s*\d+)[-\s].*$/i, "$1");

  // Сечение провода/кабеля вида "1x10", "3x2,5" иногда пишут слитно через
  // дефис сразу за маркой ("ПуВ-1x10"), а иногда через пробел ("ПуВ 1х2,5").
  // Через пробел это и так режется общим правилом ниже (токен с цифры), а
  // слитный вариант — нет, из-за чего одна и та же марка провода превращалась
  // в разные базовые имена. Отрезаем паттерн "число×число" после дефиса.
  s = s.replace(/([A-Za-zА-Яа-яЁё])-\d+(?:[.,]\d+)?[xх×]\d+(?:[.,]\d+)?\S*/gi, "$1");

  // То же самое, но точечно для щитков/корпусов ЩРн и ЩМП — "Ящик ЩРн-18" и
  // "Ящик ЩРн-24" это одна линейка щитков, число — просто ёмкость (число
  // модулей), не разные товары. Намеренно НЕ сделано общим правилом для
  // любого "короткий код + дефис + число": проверка по всей базе показала,
  // что для автоматов/контакторов/реле число после дефиса — это номинал
  // тока или типоразмер (NXB-63 и NXB-125 — разные типоразмеры автомата,
  // КМ-...220 и КМ-...380 — разное напряжение катушки), и объединять их было
  // бы уже ошибкой, способной привести к покупке не того товара.
  s = s.replace(new RegExp(`${BND_BEFORE}(ЩРн|ЩРН|ЩМП)-\\d+${BND_AFTER}`, "gi"), " $1");

  // Любые скобки целиком — внутри почти всегда упаковка/артикул/страна/доп.
  // параметр, а не идентичность товара.
  s = s.replace(/\([^)]*\)/g, " ");

  // Бренд и страна — где угодно в строке.
  s = s.replace(new RegExp(`${BND_BEFORE}(?:${BRAND_ALT})${BND_AFTER}`, "g"), " ");
  s = s.replace(new RegExp(`${BND_BEFORE}(?:${COUNTRY_ALT})${BND_AFTER}`, "g"), " ");

  s = s.replace(/["'«»,;–—]/g, " ");

  // Символы диаметра без числа рядом (Ø, ф отдельно) и голые единицы измерения,
  // оставшиеся "осиротевшими" после вырезки чисел ниже.
  s = s.replace(new RegExp(`${BND_BEFORE}[ØøФф]${BND_AFTER}`, "g"), " ");

  // ГЛАВНОЕ: любой токен, НАЧИНАЮЩИЙСЯ с цифры — это почти всегда размер/вес/
  // ток/напряжение/артикул ("3,0мм", "220/12", "16А", "2,5кг"). Токены,
  // начинающиеся с БУКВЫ, даже если содержат цифры внутри (типа "МР-3",
  // "ЩРн-12", "ВА47-19"), сознательно сохраняются — это обычно код модели/
  // серии, а не просто размер.
  s = s.replace(/(?:^|\s)\d\S*/g, " ");

  // Голые единицы измерения без числа рядом (осиротели после вырезки выше).
  s = s.replace(new RegExp(`${BND_BEFORE}(?:мм2|мм|mm|кА|kA|Вт|W|кг|шт|уп)${BND_AFTER}\\.?`, "gi"), " ");
  s = s.replace(new RegExp(`${BND_BEFORE}IP${BND_AFTER}`, "gi"), " ");

  s = s.replace(/\s+/g, " ").trim();
  s = s.replace(/[-,./()]+$/, "").trim();

  // Обрезаем до первых 2 значимых слов — вот тот самый "грубый" шаг, который
  // резко увеличивает число объединений (было: точное совпадение всего
  // очищенного названия; стало: совпадение по первым двум словам).
  // Предлоги/союзы (FILLER_WORDS) в счёт не идут — иначе одно из двух "слов"
  // тратилось бы на "по"/"для"/"с" и т.п., а настоящее различие обрезалось.
  const words = s.split(/\s+/).filter((w) => w && !FILLER_WORDS.has(w.toLowerCase()));
  let base = words.slice(0, 2).join(" ") || name;

  // Тип присоединения сантехнической арматуры (кран/муфта/вентиль и т.п.) —
  // резьбовое (ММ/МР/РМ/РР/ВР/НР — сочетание "муж./жен." концов), фланцевое
  // или "обойма-обойма" (для полиэтиленовых труб). Это РАЗНЫЙ способ монтажа,
  // не размер одного товара — фланцевый кран нельзя вкрутить туда, где нужен
  // резьбовой, и наоборот. Проверено на реальных данных: без этого уточнения
  // "Кран шаровый" сваливал резьбовые и фланцевые краны всех размеров в одну
  // группу. Диаметр (Ду) внутри каждого типа присоединения по-прежнему
  // считается вариантом — это уже отрезано общими правилами выше.
  if (/фланцев/i.test(name)) {
    base += " (фланцевый)";
  } else if (/обойма-?обойма|обойма\s*-\s*обойма/i.test(name)) {
    base += " (обойма)";
  } else {
    const connM = name.match(new RegExp(`${BND_BEFORE}(ММ|МР|РМ|РР|ВР|НР)${BND_AFTER}`));
    if (connM) base += ` (${connM[1].toUpperCase()})`;
  }

  return base;
}

// Группирует список товаров по (subcategoryId + базовое название). Один и тот
// же ключ группировки должен использоваться везде, где мы решаем, что товары
// "похожи" — иначе на странице каталога товар окажется в одной группе, а на
// странице товара — в другой/одиночной, что будет выглядеть как баг.
export function groupItems(items: PriceItem[]): ItemGroup[] {
  const groups = new Map<string, ItemGroup>();
  items.forEach((item) => {
    const base = stripToBaseName(item.name, item.attributes) || item.name;
    const key = `${item.subcategoryId || ""}::${base.toLowerCase()}`;
    if (!groups.has(key)) groups.set(key, { baseName: base, items: [] });
    groups.get(key)!.items.push(item);
  });
  return Array.from(groups.values());
}

// Находит группу, к которой принадлежит конкретный товар (по тому же ключу,
// что использует groupItems) — нужно на странице товара, чтобы показать
// остальные варианты этой же модели.
export function findGroupForItem(item: PriceItem, allItemsInSameSubcategory: PriceItem[]): ItemGroup {
  const base = stripToBaseName(item.name, item.attributes) || item.name;
  const key = `${item.subcategoryId || ""}::${base.toLowerCase()}`;
  const items = allItemsInSameSubcategory.filter((p) => {
    const pBase = stripToBaseName(p.name, p.attributes) || p.name;
    return `${p.subcategoryId || ""}::${pBase.toLowerCase()}` === key;
  });
  return { baseName: base, items };
}