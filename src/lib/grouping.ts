import { PriceItem } from "../types";

// ---------------------------------------------------------------------------
// Общая логика группировки похожих товаров (используется и в Catalog.tsx —
// список/сетка каталога, и в ProductPage.tsx — блок "похожие варианты").
// ВАЖНО: это единственное место, где живёт stripToBaseName. Если скопировать
// эту функцию в оба файла отдельно, они рано или поздно разойдутся при правке
// одного без другого, и товары на странице каталога будут группироваться
// иначе, чем на странице товара — этого не должно случиться.
// ---------------------------------------------------------------------------

export interface ItemGroup {
  baseName: string;
  items: PriceItem[];
}

const BND_BEFORE = "(?<![A-Za-zА-Яа-яЁё0-9])";
const BND_AFTER = "(?![A-Za-zА-Яа-яЁё0-9])";
function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Бренды/производители, собранные из реального каталога — режем их ГДЕ УГОДНО
// в строке (не только в конце), т.к. для расходников/крепежа и т.п. бренд
// часто не важен покупателю, и это специально решение — группировать шире,
// принимая единичные неточные объединения ради масштаба (3000+ товаров).
const KNOWN_BRANDS = [
  "TDM", "IEK", "REXANT", "Jazzway", "legrand", "KRANZ", "SHCET", "PROxima", "STARFIX",
  "CHINT", "General", "GENERICA", "OSRAM", "BYLECTRICA", "SIMPLE", "PROconnect",
  "ECOLINE", "ЗЭТАРУС", "ЭРА", "ZETKAMA", "UNIDELTA", "РВК", "Дрогол",
  "БЭЗ", "ЗУБР", "IWELD", "OLIVER", "ГАРАНТ", "Континент", "СЗСМ",
  "VERTO", "KRAFTOOL", "PATRIOT", "BOSCH", "URAGAN", "Remocolor", "Navigator",
  "ОНЛАЙТ", "ONLIGHT", "VOREL",
];
const KNOWN_COUNTRIES = [
  "Россия", "РОССИЯ", "РФ", "Китай", "КИТАЙ", "Беларусь", "БЕЛАРУСЬ", "РБ",
  "Турция", "Украина", "Франция", "Польша", "ПОЛЬША", "Италия", "Германия",
  "Чехия", "Индия", "США", "Корея", "Тайвань", "Испания", "Латвия", "Литва", "Узбекистан",
];
const BRAND_ALT = KNOWN_BRANDS.map(escapeRegExp).join("|");
const COUNTRY_ALT = KNOWN_COUNTRIES.map(escapeRegExp).join("|");

// Убирает из названия бренд/страну/скобки/любые "числовые" куски (размер, вес,
// артикул, номер модели) — то, что остаётся, обрезается до первых двух
// значимых слов. Это НАМЕРЕННО грубый инструмент: цель — минимизировать число
// карточек-дублей для крупного каталога (3000+ позиций), а не идеальная
// точность группировки. Полное название каждого товара всегда остаётся
// видно в списке вариантов на странице товара, так что даже неточная
// группировка не прячет от покупателя, что именно он выбирает — просто иногда
// в одной группе окажется на 1-2 "соседа" больше, чем формально стоило бы.
// Предлоги/союзы — сами по себе ничего не различают ("Сверло ПО металлу" vs
// "Сверло ПО дереву"), но раньше съедали одно из двух "значащих слов" в
// обрезке ниже, из-за чего оба обрубались до одинакового "Сверло по" и
// ошибочно склеивались в одну группу. Отфильтровываем их из подсчёта, чтобы
// на первое место в базовом имени попадало реальное отличие (металлу/дереву).
const STOP_WORDS = new Set(["по", "для", "с", "со", "без", "из", "от", "до", "на", "и", "в", "во"]);

// Токены-дискриминаторы: НЕ размер/артикул, а признак, который физически
// отличает один товар от другого внутри одной товарной линейки:
//  - "1Р", "2Р", "3Р", "4Р" — полюсность автоматов/выключателей нагрузки;
//  - "47-063", "57-35", "89М-100" — код серии/модели (число-дефис-число,
//    без единиц измерения рядом — размеры вида "16А"/"3,0мм" этому не
//    соответствуют, у них буква/ед. измерения приклеена без дефиса).
// Раньше оба вида токенов начинаются с цифры и попадали под общее правило
// "выкинуть всё, что начинается с цифры" — из-за этого, например, все
// автоматические выключатели (от бытового 16А/1П до промышленного 400А/3П)
// схлопывались в одну карточку на 79 позиций. Сохраняем их отдельно от
// "размерных" цифровых токенов и добавляем к базовому имени ПОСЛЕ первых
// значимых слов, а не вместо них — иначе, наоборот, можно потерять сами
// слова "Выключатель автоматический".
// Ограничил длину каждой цифровой группы до 1–3 знаков: реальные коды полюсов/
// серий автоматов такие ("57-35", "47-063"), а вот 4+-значные числа в этом же
// формате — почти всегда просто артикул детали (например "2218-0" у
// плоскогубцов), который НЕ должен считаться "серией" и отрывать товар от его
// группы — раньше отрывал.
// Убрал вариант "цифры-цифры[буквы]" (57-35, 122-1 и т.п.) совсем — та же
// форма используется и для номера СЕРИИ автомата (где это оправданно), и для
// номера МОДЕЛИ поста/розетки/etc (ПКЕ 212-2, ПКЕ 222-1...), где это тот же
// физический товар с другой конфигурацией контактов, просто с другим
// артикулом — и такие товары разваливались на карточки-одиночки. Оставил
// только "цифра+Р/P" (3Р/1Р) — полюсность реально означает разный по размеру
// и монтажу автомат, это стоит сохранять; серию/модель — нет.
const DISCRIMINATOR_RE = /^\d{1,3}[РP]$/i;

// У наконечников/гильз код вида "6-6", "35-8", "10-5" — это СЕЧЕНИЕ ПРОВОДА и
// ДИАМЕТР ШТИФТА (размер), а не код серии/модели — в отличие от автоматов
// ("ВА47-29", "57-35"), где ровно тот же по форме токен обозначает КЛАСС
// товара (разные автоматы физически несовместимы). Для наконечников/гильз
// такой токен, наоборот, должен срезаться как обычный размер — иначе один и
// тот же луженый наконечник ТМЛ разных сечений (6-6, 10-5, 35-8...) никогда
// не собирается в одну группу вариантов, хотя это буквально одна модель.
const SIZE_NOT_SERIES_RE = /наконечник|гильза/i;

// Общий шаг очистки строки (бренд/страна/скобки/цифры/мусорные фразы) —
// вынесен отдельно, т.к. вызывается дважды: один раз на исходном названии, и
// ещё раз на "восстановленном" (см. фолбэк ниже), когда настоящее название
// товара спрятано внутри скобок, а не в основном тексте.
function cleanupTokens(rawName: string, s: string, attrs?: PriceItem["attributes"]): string {
  // Синоним "Бур" = "Сверло" для буров по бетону SDS-plus/SDS-max — в прайсах
  // разных поставщиков один и тот же физический товар (насадка для перфоратора)
  // называется то "сверло", то "бур", из-за чего одинаковые по размеру
  // варианты попадали в разные группы. Нормализуем ТОЛЬКО когда в названии
  // явно есть SDS — чтобы не задеть возможный в будущем "бур" другого
  // назначения (земляной, садовый и т.п.), которого сейчас в каталоге нет.
  if (/sds/i.test(s)) {
    s = s.replace(new RegExp(`${BND_BEFORE}Бур${BND_AFTER}`, "gi"), "Сверло");
  }

  // Служебная фраза "Ввезен из РФ." / "страна происх. КИТАЙ" — метаданные
  // импорта, не название товара. Раньше слово "Ввезен" оставалось единственным
  // "значимым" словом у части товаров (у которых реальное название спрятано
  // в скобках, см. фолбэк ниже) и мешало распознать, что скобки нужно
  // разворачивать — по факту казалось, что кириллическое слово уже есть.
  s = s.replace(/ввезен\s+из\s+\S+\.?/gi, " ");
  s = s.replace(/страна\s+происх\S*\.?\s*/gi, " ");

  // Внутренний код поставщика ОНЛАЙТ ("OHT-Brd01-160", "OHT-Otd01-PZ1-80") —
  // чистый артикул, не значимое слово для покупателя. Без вырезки он остаётся
  // "вторым значимым словом" и не даёт товару без явного второго дескриптора
  // (например "Бокорезы 160мм ОНЛАЙТ OHT-Br02-160" — без слова "диэлектрические")
  // подтянуться к общей группе через фолбэк одного слова ниже.
  s = s.replace(new RegExp(`${BND_BEFORE}OHT-\\S+${BND_AFTER}`, "gi"), " ");

  if (attrs) {
    (["power", "voltage", "base", "color_temp", "current", "diameter", "material", "country"] as const).forEach((key) => {
      const val = (attrs as any)[key];
      if (!val) return;
      const pattern = escapeRegExp(String(val).trim()).replace(/\\?\s+/g, "\\s*");
      // Границы слова обязательны — без них, например, атрибут material="Сталь"
      // резал бы подстрокой и внутри слова "стальНОЙ" (Сталь+ной), превращая
      // "Фланец стальной" в "Фланец ной". Раньше это было незаметно, но после
      // обрезки базового имени до 2 слов такой огрызок становится всем, что
      // остаётся — критично для группировки.
      try {
        s = s.replace(new RegExp(`${BND_BEFORE}${pattern}${BND_AFTER}`, "gi"), " ");
      } catch {
        s = s.split(val).join(" ");
      }
    });
  }

  // Спец-случай: у насосов ЭЦВ/СПА число после буквенного кода — это класс
  // товара (диаметр скважины, физически несовместимые между собой размеры),
  // а не размер варианта одной и той же модели — его нужно сохранить.
  s = s.replace(/(ЭЦВ\s*\d+)[-\s].*$/i, "$1");
  s = s.replace(/(СПА\s*\d+)[-\s].*$/i, "$1");

  // Любые скобки целиком — внутри почти всегда упаковка/артикул/страна/доп.
  // параметр, а не идентичность товара.
  s = s.replace(/\([^)]*\)/g, " ");

  // Бренд и страна — где угодно в строке.
  s = s.replace(new RegExp(`${BND_BEFORE}(?:${BRAND_ALT})${BND_AFTER}`, "g"), " ");
  s = s.replace(new RegExp(`${BND_BEFORE}(?:${COUNTRY_ALT})${BND_AFTER}`, "g"), " ");

  s = s.replace(/["'«»,;–—]/g, " ");

  // Символы диаметра без числа рядом (Ø, ф отдельно) и голые единицы измерения,
  // оставшиеся "осиротевшими" после вырезки чисел ниже.
  s = s.replace(new RegExp(`${BND_BEFORE}[ØøФф]${BND_AFTER}`, "g"), " ");

  // ГЛАВНОЕ: любой токен, НАЧИНАЮЩИЙСЯ с цифры — это почти всегда размер/вес/
  // ток/напряжение/артикул ("3,0мм", "220/12", "16А", "2,5кг"). Токены,
  // начинающиеся с БУКВЫ, даже если содержат цифры внутри (типа "МР-3",
  // "ЩРн-12", "ВА47-19"), сознательно сохраняются — это обычно код модели/
  // серии, а не просто размер. Исключение — DISCRIMINATOR_RE (полюсность и
  // код серии без приклеенных единиц измерения): такие токены НЕ выбрасываем,
  // а оставляем на месте, чтобы забрать их отдельно после обрезки до двух
  // значимых слов (см. ниже).
  s = s.replace(/(?:^|\s)\d\S*/g, (m) => (!SIZE_NOT_SERIES_RE.test(rawName) && DISCRIMINATOR_RE.test(m.trim()) ? " " + m.trim() : " "));

  // Голые единицы измерения без числа рядом (осиротели после вырезки выше).
  s = s.replace(new RegExp(`${BND_BEFORE}(?:мм2|мм|mm|кА|kA|Вт|W|кг|шт|уп)${BND_AFTER}\\.?`, "gi"), " ");
  s = s.replace(new RegExp(`${BND_BEFORE}IP${BND_AFTER}`, "gi"), " ");

  s = s.replace(/\s+/g, " ").trim();
  s = s.replace(/[-,./()]+$/, "").trim();
  return s;
}

export function stripToBaseName(name: string, attrs?: PriceItem["attributes"]): string {
  // Один и тот же товар ("выключатель автоматический") называется у разных
  // поставщиков по-разному: полностью, "Авт.выкл.", "Авт. выкл." или просто
  // "ВА <код>". Нормализуем к одному варианту в самом начале строки, до
  // всякой другой обработки — иначе вся линейка разваливается по первому
  // слову на кучу групп вместо деления по полюсности.
  let s = name
    .replace(/^(?:Авт\.?\s*выкл\.?|Автоматический\s+выключатель|СИЛОВОЙ\s+АВТ\.?\s*ВЫКЛ\.?)/i, "Выключатель автоматический")
    .replace(/^ВА(?=[\s\d-])/, "Выключатель автоматический ВА");

  // В прайсах попадаются позиции с мусорным артикулом в самом начале
  // названия — "685200, Лампа..." или ".5000452, Мультиметр..." (с точкой
  // перед числом). Обычная числа-в-начале-токена вырезка ниже такое не
  // ловит: она требует, чтобы токен начинался СРАЗУ с цифры, а тут первый
  // символ — точка. Срезаем такой префикс явно, только в самом начале
  // строки — иначе он остаётся "первым значимым словом" и уводит товар в
  // отдельную группу-одиночку вместо той, где он реально должен быть.
  s = s.replace(/^\.?\d{3,}\s*,?\s*/, "");

  // Иногда в названии задвоено слово подряд ("Мультиметр Мультиметр ФАZА
  // цифровой...") — опечатка при выгрузке из прайса поставщика. Без дедупа
  // такое слово само по себе занимает оба "значимых" места в базовом имени
  // и не даёт товару попасть в общую группу с остальными мультиметрами.
  s = s
    .split(/\s+/)
    .filter((w, i, arr) => i === 0 || arr[i - 1].toLowerCase() !== w.toLowerCase())
    .join(" ");

  // В прайсах встречается опечатка вида "ВА 57- 35" (пробел прилип к дефису)
  // вместо "ВА 57-35" — из-за неё код серии рвётся на два токена ("57-" и
  // "35") и перестаёт опознаваться как единое целое в правиле ниже. Склеиваем
  // цифра-дефис-цифра до разбора на токены, вне зависимости от пробелов
  // вокруг дефиса.
  s = s.replace(/(\d)\s*-\s*(\d)/g, "$1-$2");

  // Составное название через дефис ("Отвертка-пробник") и то же название через
  // пробел у другого поставщика ("Отвертка пробник") — для человека одно и то
  // же слово, а для группировки — два разных "первых слова". Разбиваем дефис
  // на пробел, но ТОЛЬКО когда обе половины — чистые буквы без цифр (значит
  // это составное слово, а не код модели вроде "ОП-1" или "ВА47-29", которые
  // как раз обязаны остаться слитными — см. правило сохранения кодов ниже).
  s = s
    .split(/\s+/)
    .map((tok) => {
      if (!tok.includes("-")) return tok;
      const parts = tok.split("-");
      const allAlpha = parts.every((p) => p.length >= 2 && /^[A-Za-zА-Яа-яЁё]+$/.test(p));
      return allAlpha ? parts.join(" ") : tok;
    })
    .join(" ");

  const preprocessed = s;
  s = cleanupTokens(name, s, attrs);

  let allWords = s.split(/\s+/).filter(Boolean);
  let genericWords = allWords.filter((w) => !STOP_WORDS.has(w.toLowerCase()) && !DISCRIMINATOR_RE.test(w));

  // Некоторые прайсы (например ОНЛАЙТ) пишут настоящее название товара внутри
  // скобок в конце строки, а перед скобками — только бренд и внутренний код:
  // "ОНЛАЙТ OHT-Brd01-160 (Бокорезы диэлектрические, 160 мм)". Обычная логика
  // выше выбрасывает скобки целиком (там почти всегда артикул/упаковка), и от
  // товара остаётся "ОНЛАЙТ OHT-Brd01-160" — уникальный код, из-за которого
  // КАЖДЫЙ такой товар оказывается в отдельной группе-одиночке. Если после
  // обычной очистки среди "значимых" слов не осталось НИ ОДНОГО кириллического
  // (то есть всё, что осталось — латинские коды/бренды), а в скобках исходного
  // названия есть кириллический текст — значит настоящее описание спрятано
  // именно там. Тогда переносим его в начало строки и чистим заново. Условие
  // специально узкое (сработало только там, где без него совсем нечего
  // группировать), чтобы не задеть остальные товары, где в скобках лежит не
  // описание, а что-то постороннее (город, доп. модификатор и т.п.).
  const hasCyrillicGeneric = genericWords.some((w) => /[А-Яа-яЁё]/.test(w));
  if (!hasCyrillicGeneric) {
    const parenMatch = preprocessed.match(/\(([^)]*)\)/);
    if (parenMatch && /[А-Яа-яЁё]/.test(parenMatch[1])) {
      const promoted =
        parenMatch[1] + " " + preprocessed.slice(0, parenMatch.index) + preprocessed.slice(parenMatch.index! + parenMatch[0].length);
      s = cleanupTokens(name, promoted, attrs);
      allWords = s.split(/\s+/).filter(Boolean);
      genericWords = allWords.filter((w) => !STOP_WORDS.has(w.toLowerCase()) && !DISCRIMINATOR_RE.test(w));
    }
  }

  // Обрезаем до ПЕРВОГО значимого слова — широкая группировка "примерно
  // похожих" товаров: разные модели/бренды одного вида инструмента (отвёртки,
  // плоскогубцы и т.п.) теперь одна карточка, даже если второе слово у них
  // разное (модель, код, бренд).
  const discriminators: string[] = [];
  const seenDiscriminators = new Set<string>();
  if (!SIZE_NOT_SERIES_RE.test(name)) {
    allWords.forEach((w) => {
      // Латинскую "P" в конце (полюсность "3P") приводим к кириллической "Р"
      // ("3Р") — иначе визуально одинаковый код полюсности у разных
      // поставщиков считается двумя разными строками и рвёт группу.
      const normalized = w.replace(/P$/i, (m) => (m === "P" ? "Р" : "р"));
      if (DISCRIMINATOR_RE.test(normalized) && !seenDiscriminators.has(normalized.toLowerCase())) {
        seenDiscriminators.add(normalized.toLowerCase());
        discriminators.push(normalized);
      }
    });
  }

  // Единственное намеренное исключение из "широкой" группировки: конструкция
  // "по металлу/дереву/бетону" и SDS — они означают физически разный
  // инструмент (не взаимозаменяемый), а не просто вариант размера/бренда, и
  // должны остаться отдельными карточками, даже при группировке по одному
  // слову. Ищем "по X" БЕЗ \b — у \b Cyrillic-буквы не считаются "буквами
  // слова" в JS-регулярках, так что \bпо\b перед русским словом никогда не
  // сработает (та же ловушка, что и с задвоенными словами выше).
  const poMatch = preprocessed.match(/(?:^|\s)по\s+([А-Яа-яЁёA-Za-z]+)/i);
  if (poMatch) discriminators.push(poMatch[1].toLowerCase());
  if (/\bsds\b/i.test(name)) discriminators.push("sds");

  const base = [...genericWords.slice(0, 1)].sort((a, b) => a.localeCompare(b, "ru")).concat(discriminators).join(" ");
  return base || name;
}

// Строит карту групп по (subcategoryId + базовое название) для списка
// товаров — общая внутренняя реализация для groupItems и findGroupForItem,
// чтобы оба места гарантированно видели один и тот же результат.
//
// Раньше здесь ещё был фолбэк, "подтягивающий" одиночные группы к соседям с
// тем же первым словом — он был нужен, пока база строилась из ПЕРВЫХ ДВУХ
// значимых слов (тогда действительно бывали одиночки без второго слова).
// Теперь stripToBaseName сама берёт только одно первое слово, так что все
// товары с одинаковым первым словом и так уже в одной группе — а если у
// кого-то есть отдельный признак (по металлу/дереву/бетону, SDS), он ДОЛЖЕН
// остаться отдельно: это разный физический инструмент, а не вариант одной
// модели. Фолбэк удалён, чтобы не смешивать их обратно.
function buildGroups(items: PriceItem[]): Map<string, ItemGroup> {
  const groups = new Map<string, ItemGroup>();
  items.forEach((item) => {
    const base = stripToBaseName(item.name, item.attributes) || item.name;
    const key = `${item.subcategoryId || ""}::${base.toLowerCase()}`;
    if (!groups.has(key)) groups.set(key, { baseName: base, items: [] });
    groups.get(key)!.items.push(item);
  });
  return groups;
}

// Группирует список товаров по (subcategoryId + базовое название) — используется
// и в Catalog.tsx (список/сетка каталога), и в ProductPage.tsx (блок "похожие
// варианты"). ВАЖНО: это единственное место, где живёт логика группировки. Если
// продублировать её в обоих файлах отдельно, они рано или поздно разойдутся при
// правке одного без другого, и товары на странице каталога будут группироваться
// иначе, чем на странице товара — этого не должно случиться.
export function groupItems(items: PriceItem[]): ItemGroup[] {
  return Array.from(buildGroups(items).values());
}

// Находит группу, к которой принадлежит конкретный товар (та же логика, что и
// groupItems, включая фолбэк по одному слову) — нужно на странице товара,
// чтобы показать остальные варианты этой же модели.
export function findGroupForItem(item: PriceItem, allItemsInSameSubcategory: PriceItem[]): ItemGroup {
  const groups = buildGroups(allItemsInSameSubcategory);
  for (const g of groups.values()) {
    if (g.items.some((i) => i.id === item.id)) return g;
  }
  // Не должно случиться в норме (item всегда входит в allItemsInSameSubcategory),
  // но на всякий случай — одиночная группа из самого товара.
  const base = stripToBaseName(item.name, item.attributes) || item.name;
  return { baseName: base, items: [item] };
}